'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const {makeAddition}=require('../src/services/practice-overrides.service');
test('new question is scoped and IDs are generated by backend',()=>{
 const input={question:'Is this an original question?',subject:'Cloud',topic:'Basics',difficulty:'Easy',type:'single',options:[{id:'a',text:'Yes'},{id:'b',text:'No'},{id:'c',text:'Maybe'},{id:'d',text:'Unknown'}],correctAnswers:['a'],explanation:'Explanation here.'};
 const q=makeAddition('homepage','aws-clf-c02',input);
 assert.equal(q.groupId,'aws-clf-c02');assert.match(q.id,/^extra-/);assert.equal(q.question.id,q.id);
 assert.throws(()=>makeAddition('homepage','invalid-quiz',input),/Unknown practice quiz/);
});

test('certification inserts cannot cross assigned exams',()=> {
 const cert={exam_code:'AWS-CLF-C02',subject:'Cloud Concepts',
 question:'Which service provides compute?',options:['EC2','S3','RDS','Route 53'],
 correct_option:'A',explanation:'EC2 provides virtual machine compute.'};
 const item=makeAddition('certification','AWS-CLF-C02',cert);
 assert.equal(item.question.exam_code,'AWS-CLF-C02');
 assert.throws(()=>makeAddition('certification','AZ-900',cert),/Certification code must match/);
 assert.throws(()=>makeAddition('certification','AWS-CLF-C02',{...cert,correct_option:'E'}),/Certification questions/);
});
test('multi-answer and true/false additions preserve scoring shapes',()=> {
 const base={question:'Is the following assertion correct?',subject:'Math',topic:'Numbers',difficulty:'Medium',
 type:'true-false',options:[{id:'true',text:'True'},{id:'false',text:'False'}],
 correctAnswers:['true'],explanation:'This assertion is correct.'};
 assert.deepEqual(makeAddition('homepage','math-fundamentals',base).question.correctAnswers,['true']);
 const multi={...base,type:'multiple',options:[{id:'a',text:'One'},{id:'b',text:'Two'},
 {id:'c',text:'Three'},{id:'d',text:'Four'}],correctAnswers:['a','b']};
 assert.deepEqual(makeAddition('homepage','all-cloud',multi).question.correctAnswers,['a','b']);
});
