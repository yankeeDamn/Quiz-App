'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const {makeAddition}=require('../src/services/practice-overrides.service');
test('new question is scoped and IDs are generated by backend',()=>{
 const input={question:'Is this an original question?',subject:'Cloud',topic:'Basics',difficulty:'Easy',type:'single',options:[{id:'a',text:'Yes'},{id:'b',text:'No'},{id:'c',text:'Maybe'},{id:'d',text:'Unknown'}],correctAnswers:['a'],explanation:'Explanation here.'};
 const q=makeAddition('homepage','aws-clf-c02',input);
 assert.equal(q.groupId,'aws-clf-c02');assert.match(q.id,/^extra-/);assert.equal(q.question.id,q.id);
 assert.throws(()=>makeAddition('homepage','invalid-quiz',input),/Unknown practice quiz/);
});
