'use strict';
const {Router}=require('express');
const {rateLimit}=require('express-rate-limit');
const {authenticateNextAuth}=require('../middleware/nextauth');
const s=require('../services/institutes/foundation');
const router=Router();
const wrap=fn=>(req,res,next)=>Promise.resolve(fn(req,res)).catch(next);
const ok=(res,data,status=200)=>res.status(status).json({success:true,data});
router.use((req,res,next)=>/^\/(institutes|platform\/institutes)(\/|$)/.test(req.path)?next():next('router'));
router.use((_req,res,next)=>{res.set('Cache-Control','private, no-store');next();});
router.use((_req,res,next)=>process.env.INSTITUTES_ENABLED==='true'?next():res.status(404).json({success:false,error:{message:'Institute workspace is not enabled'}}));
router.get('/institutes/public/:slug',wrap(async(req,res)=>ok(res,await s.publicProfile(req.params.slug))));
router.use(authenticateNextAuth);
router.use(rateLimit({windowMs:60000,limit:120,keyGenerator:req=>req.user.id,standardHeaders:'draft-7',legacyHeaders:false}));
router.use(require('./institute-delivery'));
router.get('/institutes/my',wrap(async(req,res)=>ok(res,{institutes:await s.mine(req.user)})));
router.post('/institutes/applications',wrap(async(req,res)=>ok(res,await s.apply(req.user,req.body),201)));
router.post('/institutes/invitations/accept',wrap(async(req,res)=>ok(res,await s.accept(req.user,req.body.token))));
router.get('/platform/institutes/applications',wrap(async(req,res)=>ok(res,{applications:await s.applications(req.user)})));
router.post('/platform/institutes/applications/:id/review',wrap(async(req,res)=>ok(res,await s.review(req.user,req.params.id,req.body.action))));
router.post('/platform/institutes/:id/lifecycle',wrap(async(req,res)=>ok(res,await s.lifecycle(req.user,req.params.id,req.body.status))));
router.get('/institutes/:slug/workspace',wrap(async(req,res)=>ok(res,await s.workspace(req.user,req.params.slug))));
router.put('/institutes/:slug/settings',wrap(async(req,res)=>ok(res,await s.settings(req.user,req.params.slug,req.body))));
router.get('/institutes/:slug/members',wrap(async(req,res)=>ok(res,{members:await s.members(req.user,req.params.slug,req.query)})));
router.post('/institutes/:slug/members/:id/revoke',wrap(async(req,res)=>ok(res,await s.revokeMember(req.user,req.params.slug,req.params.id))));
router.get('/institutes/:slug/invitations',wrap(async(req,res)=>ok(res,{invitations:await s.invitations(req.user,req.params.slug)})));
router.post('/institutes/:slug/invitations',wrap(async(req,res)=>ok(res,await s.invite(req.user,req.params.slug,req.body),201)));
router.post('/institutes/:slug/invitations/:id/revoke',wrap(async(req,res)=>ok(res,await s.revokeInvite(req.user,req.params.slug,req.params.id))));
module.exports=router;
